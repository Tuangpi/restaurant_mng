export function t(language: Language, key: string, params?: Record<string, string>): string {
  let text = translations[language]?.[key] || translations.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{{${k}}}`, v);
    }
  }
  return text;
}

export function formatMoney(amount: number, language: Language = "en"): string {
  return `${amount.toLocaleString(language === "my" ? "my-MM" : "en-US")} ${t(language, "mmk")}`;
}